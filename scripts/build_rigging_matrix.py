"""Build docs/rigging_matrix.md and docs/rigging_matrix.csv: one row per rigging feature, one column group per application.

    python scripts/build_rigging_matrix.py

Every cell is computed from the repository (catalog, knowledge base, parser, tests, real-run fixtures), nothing is typed by hand, so the matrix can be
regenerated after any change. Cell codes are explained at the top of the generated markdown.
"""
from __future__ import annotations

import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from ingestion.features import APPS, load_catalog  # noqa: E402
from ingestion.rigging_knowledge import load as load_kb  # noqa: E402
from ingestion.terms import suggest_feature  # noqa: E402

# Real-application checks: the generic harness (verification/) exists for these apps; whether it was RUN per feature is listed in LIVE_APP_CHECKED.
HARNESS_TESTED = {"blender": True, "houdini": True, "maya": False}      # test_verification.py ran against the real application (Maya: not installed yet)
LIVE_APP_CHECKED: dict[tuple[str, str], str] = {}                      # (feature, app) -> note; empty: no feature has been checked inside a real application


def live_runs() -> dict[tuple[str, str], list[str]]:
    """(feature_id, app) -> the real-run fixtures whose steps carry that feature id."""
    out: dict[tuple[str, str], list[str]] = defaultdict(list)
    for p in sorted((ROOT / "tests/fixtures/real_runs").glob("R*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        for s in d.get("steps") or []:
            if isinstance(s, dict) and s.get("feature_id"):
                out[(s["feature_id"], d.get("app", "blender"))].append(p.name.split("_")[0])
    return out


def test_mentions() -> dict[str, int]:
    text = "\n".join(p.read_text(encoding="utf-8", errors="ignore") for p in (ROOT / "tests").glob("test_*.py"))
    return {m: text.count(m) for m in set(re.findall(r"\b[A-Z]{4}-\d{2}\b", text))}


def build() -> tuple[list[dict], dict]:
    cat, kb = load_catalog(), load_kb()
    runs, mentions = live_runs(), test_mentions()
    rows = []
    for f in cat.features:
        row = {"id": f.id, "category": f.category, "name": f.name, "priority": f.priority, "phase": f.phase, "mvp": "yes" if f.mvp else "", "offline_test_mentions": mentions.get(f.id, 0)}
        for app in APPS:
            code = f.support_code(app)
            entries = [e for e in kb.entries if f.id in e.features and app in e.apps]
            phrases = [p for e in entries for p in e.phrases]
            if code == "U":
                parser = "n/a"
            elif any(suggest_feature(p, app) == f.id for p in phrases):
                parser = "kb-phrase"
            elif suggest_feature(f.name, app) == f.id:
                parser = "name"
            else:
                parser = "none"
            effects = any(f.id in e.effects for e in entries)
            row[f"{app}_catalog"] = code
            row[f"{app}_kb_entries"] = len(entries)
            row[f"{app}_kb_depth"] = sum(bool(e.troubleshooting) for e in entries) and "trouble" or ("verify" if any(e.verify for e in entries) else ("basic" if entries else "none"))
            row[f"{app}_parser"] = parser
            row[f"{app}_derived_state"] = "yes" if effects else ""
            row[f"{app}_real_app_check"] = LIVE_APP_CHECKED.get((f.id, app), "not run")
            row[f"{app}_live_run"] = ",".join(sorted(set(runs.get((f.id, app), [])))) or "none"
        rows.append(row)
    return rows, {"harness_tested": HARNESS_TESTED}


def write_csv(rows: list[dict], path: Path) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def short(row: dict, app: str) -> str:
    if row[f"{app}_catalog"] == "U":
        return "U"
    kbm = {"none": "-", "basic": "k", "verify": "kv", "trouble": "kt"}[row[f"{app}_kb_depth"]]
    p = {"none": "-", "name": "n", "kb-phrase": "p", "n/a": "-"}[row[f"{app}_parser"]]
    live = row[f"{app}_live_run"]
    return f"{row[f'{app}_catalog']} {kbm} {p}{' d' if row[f'{app}_derived_state'] else ''}{' L' if live != 'none' else ''}"


def write_md(rows: list[dict], path: Path) -> None:
    n = len(rows)
    L = ["# Rigging feature x application matrix", "",
         "Generated by `scripts/build_rigging_matrix.py` from the repository. Do not edit by hand; run the script again. CSV with every column: `docs/rigging_matrix.csv`.", "",
         "## How to read a cell", "",
         "`C K P d L` per application:", "",
         "- **C** catalog support from the feature spec: N native, P partial, C custom/add-on, U unsupported (then the rest is blank).",
         "- **K** knowledge base (`knowledge/rigging_knowledge.json`): `-` nothing, `k` entry with facts/mistakes, `kv` also has a verify line, `kt` also has a troubleshooting item.",
         "- **P** parser: can `terms.suggest_feature` tag spoken/written wording as this feature? `p` from a researched phrase, `n` from the catalog name only, `-` no. `n` is an UPPER BOUND (a feature's own title always matches itself); real-speech accuracy is measured elsewhere (Maya only: precision 63.6%, recall 53.8% on 52 labelled moments).",
         "- **d** a derived node state exists for this feature in this app (`effects` in the knowledge base), so the scene-chain check and the harness have something to test.",
         "- **L** this feature appears in a saved real Gemini run for this application (`tests/fixtures/real_runs`).", "",
         "Not in the cell because it is the same everywhere: offline tests mention the feature id (CSV `offline_test_mentions`), and the real-application harness",
         "(`verification/`) has been run against real Blender 5.2.2 and Houdini 22.0.466 for the predicate kinds listed in its tests. **No individual feature has been checked inside a",
         "real application yet** (CSV `*_real_app_check` is `not run` everywhere). Maya was not installed when this was written.", ""]
    L += ["## Totals", "", "| | Blender | Maya | Houdini |", "|---|---|---|---|"]
    def tot(label, fn):
        L.append(f"| {label} | " + " | ".join(str(fn(a)) for a in APPS) + " |")
    tot("features supported (catalog N/P/C)", lambda a: sum(r[f"{a}_catalog"] != "U" for r in rows))
    tot("with a knowledge-base entry", lambda a: sum(r[f"{a}_kb_entries"] > 0 for r in rows))
    tot("with a troubleshooting item", lambda a: sum(r[f"{a}_kb_depth"] == "trouble" for r in rows))
    tot("parser can tag it", lambda a: sum(r[f"{a}_parser"] in ("name", "kb-phrase") for r in rows))
    tot("derived node state", lambda a: sum(bool(r[f"{a}_derived_state"]) for r in rows))
    tot("seen in a real Gemini run", lambda a: sum(r[f"{a}_live_run"] != "none" for r in rows))
    tot("checked inside the real application", lambda a: sum(r[f"{a}_real_app_check"] != "not run" for r in rows))
    L += ["", f"Total features: {n}. P0: {sum(r['priority'] == 'P0' for r in rows)}, P1: {sum(r['priority'] == 'P1' for r in rows)}, MVP: {sum(bool(r['mvp']) for r in rows)}.", ""]
    L += ["## Gaps that matter most: P0/P1 features the application supports but nothing in the knowledge base covers", "", "| Feature | Priority | Blender | Maya | Houdini |", "|---|---|---|---|---|"]
    gaps = [r for r in rows if r["priority"] in ("P0", "P1") and any(r[f"{a}_catalog"] != "U" and r[f"{a}_kb_entries"] == 0 for a in APPS)]
    for r in gaps:
        cells = [("GAP" if r[f"{a}_catalog"] != "U" and r[f"{a}_kb_entries"] == 0 else ("covered" if r[f"{a}_kb_entries"] else "U")) for a in APPS]
        L.append(f"| {r['id']} {r['name'][:48]} | {r['priority']} | " + " | ".join(cells) + " |")
    L += ["", f"{len(gaps)} of the {sum(r['priority'] in ('P0', 'P1') for r in rows)} P0/P1 features have at least one supported application with no knowledge-base entry.", ""]
    by = defaultdict(list)
    for r in rows:
        by[r["category"]].append(r)
    L += ["## Full matrix", ""]
    for c, rs in by.items():
        L += [f"### {c}", "", "| ID | Feature | Pri | Blender | Maya | Houdini |", "|---|---|---|---|---|---|"]
        L += [f"| {r['id']} | {r['name'][:60]} | {r['priority']}{'*' if r['mvp'] else ''} | " + " | ".join(short(r, a) for a in APPS) + " |" for r in rs]
        L.append("")
    L.append("`*` = in the MVP set of the feature spec.")
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    rows, _ = build()
    write_csv(rows, ROOT / "docs/rigging_matrix.csv")
    write_md(rows, ROOT / "docs/rigging_matrix.md")
    print(f"wrote {len(rows)} rows to docs/rigging_matrix.md and .csv")
